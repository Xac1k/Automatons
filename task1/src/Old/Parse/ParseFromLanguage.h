enum class Side {right, left};

// ============================================================================
//                           ФОРМАТ ВВОДА (ГРАММАТИКА)
// ============================================================================
//
// ┌── side: left ────────────────────────────────────────────────────────────┐
// │ language:                                                                │
// │   S -> S.a | S.b | C.c                                                   │
// │   A -> B.a | S.b | OUTPUT.c                                              │
// │   B -> B.b | B.a | S.c | OUTPUT.b                                        │
// │   C -> A.a | B.b | S.c | OUTPUT.a                                        │
// └──────────────────────────────────────────────────────────────────────────┘
//
// ┌── side: right ───────────────────────────────────────────────────────────┐
// │ language:                                                                │
// │   S -> a.S | b.S | c.C                                                   │
// │   A -> a.B | b.S | c.OUTPUT                                              │
// │   B -> b.B | a.B | c.S | b.OUTPUT                                        │
// │   C -> a.A | b.B | c.S | a.OUTPUT                                        │
// └──────────────────────────────────────────────────────────────────────────┘
//
// ----------------------------------------------------------------------------
//  ПОЯСНЕНИЯ
// ----------------------------------------------------------------------------
//  • Первая строка — аксиома, с которой начинается разбор.
//
//  • OUTPUT — выход: только терминальный символ, без замены на нетерминал.
//
//  • Важно явно указать вариант языка:
//        ▸ правосторонний  (right)
//        ▸ левосторонний   (left)
//
//  • Для правостороннего языка обход идёт с терминала, т.е. с OUTPUT.
//
//  • Для левостороннего языка обход идёт с аксиомы, т.е. с первой строки.
//
// ============================================================================
AutomatonMoore ParseFromLanguage(Side side, const std::string& language);
